test("quickMeta reads the folder, branch, start and entrypoint from the first records only", () => {
  const t = make({ entrypoint: "claude-desktop", branch: "feat/x" });
  t.bookkeeping();
  t.prompt("hi");
  const meta = quickMeta(write(t.lines()));
  assert.equal(meta.cwd, "C:\\Users\\Test User\\My Project");
  assert.equal(meta.branch, "feat/x");
  assert.equal(meta.entrypoint, "claude-desktop");
  assert.ok(meta.started.startsWith("2026-10-01"));
  assert.deepEqual(quickMeta(write("")), { cwd: "", branch: "", started: "", entrypoint: "" });
});

test("entrypoints: the app that started the session, from the start and from the end of the file", () => {
  const a = make({ entrypoint: "cli" });
  a.prompt("x");
  assert.deepEqual(entrypoints(write(a.lines())), { first: "cli", last: "cli" });
  // continued in another app: the first record says cli, the last one claude-desktop
  const head = make({ entrypoint: "cli" });
  head.prompt("start");
  const tail = make({ entrypoint: "claude-desktop" });
  tail.prompt("later");
  const mixed = head.lines() + "x".repeat(200 * 1024) + "\n" + tail.lines();
  assert.deepEqual(entrypoints(write(mixed)), { first: "cli", last: "claude-desktop" });
  assert.deepEqual(entrypoints(write("{}\n")), { first: "", last: "" });
  assert.deepEqual(entrypoints(path.join(dir, "missing.jsonl")), { first: "", last: "" });
});

test("lastActivity is the newest timestamp near the end of the file", () => {
  const t = make({ start: "2026-10-01T09:00:00.000Z", stepMs: 60000 });
  t.prompt("a"); t.say("b"); t.prompt("c");
  const last = t.records.at(-1).timestamp;
  assert.equal(lastActivity(write(t.lines())), Date.parse(last));
  assert.ok(Number.isNaN(lastActivity(write("{}\n"))));
  // a timestamp far from the end (more than 64 KB back) is found by the second, wider look
  assert.equal(lastActivity(write(`${JSON.stringify({ timestamp: "2026-09-01T00:00:00.000Z" })}\n${"y".repeat(100 * 1024)}\n`)), Date.parse("2026-09-01T00:00:00.000Z"));
});

