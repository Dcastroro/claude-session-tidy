import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { customTitleFile, entrypoints, lastActivity, pickTitle, promptOf, quickMeta, scanTranscript, titleOf } from "../src/transcript.mjs";
import { Transcript, tmpDir } from "./helpers.mjs";

const dir = tmpDir("cst-tr-");
let n = 0;
function write(text) {
  const file = path.join(dir, `t${n++}.jsonl`);
  fs.writeFileSync(file, text);
  return file;
}
const make = (opts = {}) => new Transcript({ id: `s${n}`, cwd: "C:\\Users\\Test User\\My Project", ...opts });

test("promptOf: what the person typed counts, what Claude Code wrote in their name does not", () => {
  const user = (content, extra = {}) => ({ type: "user", message: { role: "user", content }, ...extra });
  assert.deepEqual(promptOf(user("fix the bug")), { kind: "prompt", text: "fix the bug" });
  assert.deepEqual(promptOf(user([{ type: "text", text: "with blocks" }])), { kind: "prompt", text: "with blocks" });
  assert.deepEqual(promptOf(user("<command-message>review</command-message>\n<command-name>/review</command-name>\n<command-args>src</command-args>")), { kind: "command", text: "/review src" });
  assert.deepEqual(promptOf(user("<command-name>/clear</command-name><command-args></command-args>")), { kind: "command", text: "/clear" });
  assert.deepEqual(promptOf(user("<bash-input>git status</bash-input>")), { kind: "bash", text: "! git status" });
  assert.deepEqual(promptOf(user([{ type: "image", source: { type: "base64", media_type: "image/png", data: "AA==" } }])), { kind: "prompt", text: "(image)" });
  assert.deepEqual(promptOf(user("<system-reminder>be careful</system-reminder>\nreal text")), { kind: "prompt", text: "real text" });
  for (const nope of [
    user([{ type: "tool_result", tool_use_id: "t1", content: "output" }]),
    user("<bash-stdout>x</bash-stdout><bash-stderr></bash-stderr>"),
    user("<local-command-stdout>done</local-command-stdout>"),
    user("<local-command-caveat>Caveat: do not respond</local-command-caveat>"),
    user("Caveat: The messages below were generated by the user"),
    user([{ type: "text", text: "[Request interrupted by user]" }]),
    user("<system-reminder>only a reminder</system-reminder>"),
    user("<ide_opened_file>The user opened a.ts</ide_opened_file>"),
    user([{ type: "text", text: "meta text" }], { isMeta: true }),
    user("summary of the past", { isCompactSummary: true }),
    user("from a subagent", { isSidechain: true }),
    { type: "assistant", message: { content: "hi" } },
    user(""), user([]), user(null), null, undefined,
  ]) assert.equal(promptOf(nope), null, JSON.stringify(nope));
});

test("titles: /rename beats Claude's title beats an old summary beats the first prompt", () => {
  assert.deepEqual(titleOf({ type: "custom-title", customTitle: "Mine" }), { custom: "Mine" });
  assert.deepEqual(titleOf({ type: "ai-title", aiTitle: "Theirs" }), { ai: "Theirs" });
  assert.deepEqual(titleOf({ type: "summary", summary: "short line" }), { summary: "short line" });
  assert.equal(titleOf({ type: "summary", summary: "x".repeat(200) }), null, "a long summary is a compaction summary");
  assert.equal(titleOf({ type: "custom-title", customTitle: "" }), null);
  assert.equal(titleOf({ type: "user" }), null);
  assert.equal(pickTitle({ custom: "A", ai: "B" }, "p"), "A");
  assert.equal(pickTitle({ ai: "B", summary: "C" }, "p"), "B");
  assert.equal(pickTitle({ summary: "C" }, "p"), "C");
  assert.equal(pickTitle({}, "  first   prompt\nlines "), "first prompt lines");
  assert.equal(pickTitle({}, ""), "(untitled session)");
  assert.equal(pickTitle({}, "x".repeat(200)).length, 70);
});

test("scanTranscript counts prompts, finds the title, the folder and the first prompt", () => {
  const t = make();
  t.bookkeeping();
  t.prompt("Fix the login redirect loop");
  t.say("On it.");
  t.run("Bash", { command: "ls" }, "a\nb");
  t.systemReminder("remember");
  t.caveat();
  t.command("review", "src");
  t.commandOutput("done");
  t.bashInput("git status");
  t.bashOutput("clean");
  t.interrupt();
  t.prompt("second prompt");
  t.say("fine");
  t.aiTitle("Claude's title");
  t.customTitle("My own title");
  const info = scanTranscript(write(t.lines()));
  assert.equal(info.prompts, 4, "two typed prompts, one slash command, one ! command");
  assert.equal(info.firstPrompt, "Fix the login redirect loop");
  assert.equal(info.hasAssistant, true);
  assert.equal(info.cwd, "C:\\Users\\Test User\\My Project");
  assert.equal(info.branch, "main");
  assert.ok(info.started.startsWith("2026-10-01"));
  assert.equal(pickTitle(info.titles, info.firstPrompt), "My own title");
  assert.equal(info.readable, true);
});

test("scanTranscript: a session with nothing typed has zero prompts, and sidechain records are not counted", () => {
  const t = make();
  t.bookkeeping();
  assert.equal(scanTranscript(write(t.lines())).prompts, 0);
  const s = make();
  s.prompt("real");
  const sub = s.prompt("from a subagent");
  sub.isSidechain = true;
  assert.equal(scanTranscript(write(s.lines())).prompts, 1);
  assert.equal(scanTranscript(write("")).prompts, 0);
});

test("scanTranscript stops at the first prompt when asked", () => {
  const t = make();
  t.prompt("one"); t.say("a"); t.prompt("two"); t.prompt("three");
  const info = scanTranscript(write(t.lines()), { stopAtPrompt: true });
  assert.equal(info.prompts, 1);
});

test("scanTranscript copes with Windows line endings, a byte-order mark, garbage lines and a huge line", () => {
  const t = make();
  t.prompt("hello");
  t.say("world");
  t.run("Bash", { command: "big" }, "x".repeat(3 * 1024 * 1024));
  t.prompt("after the huge line");
  const [first, ...rest] = t.lines().split("\n");
  const text = `\ufeff${first}\r\nnot json at all\r\n{"half":\r\n${rest.join("\r\n")}\r\n\r\n`;
  const info = scanTranscript(write(text));
  assert.equal(info.prompts, 2);
  assert.equal(info.cwd, "C:\\Users\\Test User\\My Project");
});

