test("300 corrupted transcripts never make a scanner throw, and the answers keep their shape", () => {
  let seed = 99;
  const rnd = () => { seed = (seed * 1664525 + 1013904223) >>> 0; return seed / 4294967296; };
  const t = make({ entrypoint: "claude-desktop" });
  t.bookkeeping();
  for (let i = 0; i < 12; i++) { t.prompt(`prompt ${i}`); t.say("answer"); t.run("Bash", { command: "ls" }, "output\n".repeat(20)); }
  t.customTitle("A title");
  const clean = t.lines();
  const noise = ["", "{", "}", "[", '{"type":"user"', '{"type":"user","message":null}', '{"type":"user","message":{"content":[null,1,"x",{"type":"text"}]}}', '"just a string"', "null", "12", "\u0000\u0001\u0002", "��", '{"timestamp":"2026-13-45T99:99:99Z"}', '{"cwd":5,"entrypoint":{},"timestamp":[]}'];
  for (let n = 0; n < 300; n++) {
    let text = clean;
    for (let k = Math.floor(rnd() * 4); k >= 0; k--) {
      const at = Math.floor(rnd() * text.length);
      const kind = Math.floor(rnd() * 5);
      if (kind === 0) text = text.slice(0, at);
      else if (kind === 1) text = text.slice(0, at) + text.slice(at + 1 + Math.floor(rnd() * 200));
      else if (kind === 2) text = text.slice(0, at) + noise[Math.floor(rnd() * noise.length)] + "\n" + text.slice(at);
      else if (kind === 3) text = text.replace(/\n/g, rnd() < 0.5 ? "\r\n" : "");
      else text = text.slice(0, at) + String.fromCharCode(Math.floor(rnd() * 0xffff)) + text.slice(at);
    }
    const file = write(text);
    const info = scanTranscript(file);
    assert.ok(Number.isInteger(info.prompts) && info.prompts >= 0 && info.prompts <= 12, `${n}: ${info.prompts}`);
    assert.equal(typeof info.cwd, "string");
    assert.equal(typeof info.readable, "boolean");
    assert.ok(scanTranscript(file, { stopAtPrompt: true }).prompts <= 1);
    const meta = quickMeta(file);
    assert.ok(typeof meta.cwd === "string" && typeof meta.entrypoint === "string");
    const ep = entrypoints(file);
    assert.ok(typeof ep.first === "string" && typeof ep.last === "string");
    const last = lastActivity(file);
    assert.ok(Number.isNaN(last) || Number.isFinite(last));
    pickTitle(info.titles, info.firstPrompt);
  }
});
