// Synthetic Claude Code transcripts and the files that go with them, shaped like Claude Code 2.1.x writes
// them. Everything in them is invented. write() puts files only under the config folder it is given.
import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";
import { projectSlug } from "../src/config.mjs";

// A repeatable UUID: the same seed and counter always give the same id.
export function uuid(seed, n = 0) {
  const x = createHash("sha1").update(`${seed}:${n}`).digest("hex");
  return `${x.slice(0, 8)}-${x.slice(8, 12)}-4${x.slice(13, 16)}-${"89ab"[parseInt(x[16], 16) % 4]}${x.slice(17, 20)}-${x.slice(20, 32)}`;
}

export class Transcript {
  // cwd: the project folder the session ran in. start: when it began (ISO). stepMs: time between records.
  constructor({ id, seed, cwd, entrypoint = "cli", branch = "main", version = "2.1.295", start = "2026-10-01T09:00:00.000Z", stepMs = 20000 }) {
    this.seed = seed || id || "session";
    this.id = id || uuid(this.seed, 0);
    this.cwd = cwd;
    this.entrypoint = entrypoint;
    this.branch = branch;
    this.version = version;
    this.clock = Date.parse(start);
    this.stepMs = stepMs;
    this.records = [];
    this.parent = null;
    this.counter = 1;
    this.msgCounter = 1;
    this.toolCounter = 1;
  }

  now() { const t = new Date(this.clock).toISOString(); this.clock += this.stepMs; return t; }
  skip(ms) { this.clock += ms; return this; }

  // A record in the conversation chain: it points at the previous one.
  chain(fields) {
    const rec = {
      parentUuid: this.parent, isSidechain: false, userType: "external", entrypoint: this.entrypoint, cwd: this.cwd,
      sessionId: this.id, version: this.version, gitBranch: this.branch, ...fields, uuid: uuid(this.seed, this.counter++), timestamp: this.now(),
    };
    this.records.push(rec);
    this.parent = rec.uuid;
    return rec;
  }
  // A bookkeeping record: not part of the conversation.
  side(fields) { const rec = { sessionId: this.id, ...fields }; this.records.push(rec); return rec; }
  raw(rec) { this.records.push(rec); return rec; }

  // --- the person ---------------------------------------------------------------------------
  user(content, extra = {}) { return this.chain({ type: "user", message: { role: "user", content }, ...extra }); }
  prompt(text) { return this.user(text, { permissionMode: "default" }); }
  command(name, args = "") {
    const bare = name.replace(/^\//, "");
    return this.user(`<command-message>${bare}</command-message>\n<command-name>/${bare}</command-name>\n<command-args>${args}</command-args>`);
  }
  commandOutput(text) { return this.user(`<local-command-stdout>${text}</local-command-stdout>`); }
  caveat() { return this.user("<local-command-caveat>Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages.</local-command-caveat>", { isMeta: true }); }
  bashInput(cmd) { return this.user(`<bash-input>${cmd}</bash-input>`); }
  bashOutput(stdout, stderr = "") { return this.user(`<bash-stdout>${stdout}</bash-stdout><bash-stderr>${stderr}</bash-stderr>`); }
  interrupt() { return this.user([{ type: "text", text: "[Request interrupted by user]" }]); }
  systemReminder(text) { return this.user([{ type: "text", text: `<system-reminder>${text}</system-reminder>` }], { isMeta: true }); }
  image(text = "") {
    const blocks = [{ type: "image", source: { type: "base64", media_type: "image/png", data: "iVBORw0KGgo=" } }];
    if (text) blocks.push({ type: "text", text });
    return this.user(blocks);
  }

  // --- Claude -------------------------------------------------------------------------------
  assistant(blocks, { stop = "end_turn" } = {}) {
    const n = this.msgCounter++;
    return blocks.map((b, i) => this.chain({
      type: "assistant", requestId: `req_${n}`,
      message: { id: `msg_${this.seed.slice(0, 6)}${n}`, type: "message", role: "assistant", model: "claude-opus-5-5", content: [b], stop_reason: i === blocks.length - 1 ? stop : null, stop_sequence: null, usage: { input_tokens: 10, output_tokens: 5 } },
    }));
  }
  say(text) { return this.assistant([{ type: "text", text }]); }
  tool(name, input) {
    const id = `toolu_${this.seed.slice(0, 6)}${this.toolCounter++}`;
    this.assistant([{ type: "tool_use", id, name, input }], { stop: "tool_use" });
    return id;
  }
  result(toolId, content) { return this.chain({ type: "user", message: { role: "user", content: [{ type: "tool_result", tool_use_id: toolId, content }] } }); }
  run(name, input, output) { const id = this.tool(name, input); this.result(id, output); return id; }

  // --- the rest -----------------------------------------------------------------------------
  customTitle(title) { return this.side({ type: "custom-title", customTitle: title }); }
  aiTitle(title) { return this.side({ type: "ai-title", aiTitle: title }); }
  summary(text) { return this.side({ type: "summary", summary: text, leafUuid: this.parent }); }
  compact(summary = "The conversation so far.") {
    this.parent = null;
    this.chain({ type: "system", subtype: "compact_boundary", content: "Conversation compacted", compactMetadata: { trigger: "auto", preTokens: 167000 } });
    return this.user([{ type: "text", text: `This session is being continued from a previous conversation. Summary:\n${summary}` }], { isCompactSummary: true });
  }
  // The bookkeeping records Claude Code keeps beside the conversation.
  bookkeeping() {
    this.side({ type: "queue-operation", operation: "enqueue", timestamp: this.now(), content: "queued" });
    this.side({ type: "file-history-snapshot", messageId: "m1", snapshot: { messageId: "m1", trackedFileBackups: {}, timestamp: this.now() }, isSnapshotUpdate: false });
    this.side({ type: "last-prompt", lastPrompt: "x", leafUuid: this.parent });
    return this;
  }

  lines() { return `${this.records.map((r) => JSON.stringify(r)).join("\n")}\n`; }

  // Writes <configDir>/projects/<slug>/<id>.jsonl and returns where. `mtime` (ms) sets the file's time;
  // by default it is the time of the last record.
  write(configDir, { mtime, text } = {}) {
    const slug = projectSlug(this.cwd);
    const dir = path.join(configDir, "projects", slug);
    fs.mkdirSync(dir, { recursive: true });
    const file = path.join(dir, `${this.id}.jsonl`);
    fs.writeFileSync(file, text ?? this.lines());
    const t = new Date(mtime ?? this.clock);
    fs.utimesSync(file, t, t);
    return { id: this.id, file, dir, slug, transcript: this };
  }
}

// --- everything that belongs to a session besides the transcript -------------------------------

const put = (file, text, mtime) => {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
  if (mtime !== undefined) fs.utimesSync(file, new Date(mtime), new Date(mtime));
};

// Creates the folders and files Claude Code keeps for session `id` of project folder `slug`, and returns their
// paths relative to the config folder (forward slashes). `mtime` (ms) is put on every file.
export function addCompanions(configDir, slug, id, { mtime, title = "From the title file" } = {}) {
  const rel = [
    `projects/${slug}/${id}/subagents/agent-a1b2c3.jsonl`,
    `projects/${slug}/${id}/subagents/agent-a1b2c3.meta.json`,
    `projects/${slug}/${id}/tool-results/toolu_01.txt`,
    `projects/${slug}/${id}/tool-results/toolu_02.txt`,
    `projects/${slug}/${id}/custom-title.json`,
    `file-history/${id}/0fb339eae9426361@v1`,
    `file-history/${id}/0fb339eae9426361@v2`,
    `session-env/${id}/env.sh`,
    `uploads/${id}/shot.png`,
    `tasks/${id}/1.json`,
    `todos/${id}-agent-${id}.json`,
    `debug/${id}.txt`,
    `usage-data/facets/${id}.json`,
    `usage-data/session-meta/${id}.json`,
  ];
  for (const r of rel) {
    const body = r.endsWith("custom-title.json") ? JSON.stringify({ customTitle: title }) : `content of ${r}`;
    put(path.join(configDir, ...r.split("/")), body, mtime);
  }
  return rel;
}

// Files that sit near a session but are not its own, and must survive anything done to it.
export function addBystanders(configDir, slug, otherId) {
  const rel = [
    `projects/${slug}/memory/MEMORY.md`,
    `plans/some-plan.md`,
    `paste-cache/abc123.txt`,
    `shell-snapshots/snapshot-bash-1700000000000-abc123.sh`,
    `history.jsonl`,
    `todos/${otherId}-agent-${otherId}.json`,
    `file-history/${otherId}/ffff@v1`,
    `sessions/12345.json`,
  ];
  for (const r of rel) put(path.join(configDir, ...r.split("/")), `bystander ${r}`);
  return rel;
}

// A flat listing of every file below `dir`: relative path (forward slashes) -> { size, mtimeMs, text }.
export function snapshot(dir) {
  const out = {};
  const walk = (d) => {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const p = path.join(d, e.name);
      if (e.isDirectory()) { walk(p); continue; }
      const st = fs.statSync(p);
      out[path.relative(dir, p).split(path.sep).join("/")] = { size: st.size, mtimeMs: Math.round(st.mtimeMs), text: fs.readFileSync(p, "utf8") };
    }
  };
  if (fs.existsSync(dir)) walk(dir);
  return out;
}
